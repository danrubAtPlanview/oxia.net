#!/usr/bin/env python3
"""Turns BenchmarkDotNet *-report-full-compressed.json files into docs/benchmark-results.md.

usage: python benchmarks/make-results-doc.py <bdn-artifacts-dir> <output.md> [extra-section.md ...]
The extra sections (alloc profile, load runs) are appended verbatim.
"""
import glob
import json
import os
import sys


def fmt_time(ns):
    if ns is None:
        return "n/a"
    if ns >= 1e6:
        return f"{ns / 1e6:,.2f} ms"
    if ns >= 1e3:
        return f"{ns / 1e3:,.2f} us"
    return f"{ns:,.1f} ns"


def fmt_bytes(b):
    if b is None:
        return "n/a"
    if b >= 1024 * 1024:
        return f"{b / 1024 / 1024:,.2f} MB"
    if b >= 1024:
        return f"{b / 1024:,.2f} KB"
    return f"{b:,.0f} B"


def main():
    art, out = sys.argv[1], sys.argv[2]
    extras = sys.argv[3:]
    files = sorted(glob.glob(os.path.join(art, "results", "*-report-full-compressed.json")))
    host = None
    sections = []
    total = 0
    for f in files:
        data = json.load(open(f, encoding="utf-8"))
        host = host or data.get("HostEnvironmentInfo")
        title = data["Title"].split("-")[0]
        cls = title.replace("Oxia.Client.Benchmarks.", "")
        rows = []
        for b in data["Benchmarks"]:
            st = b.get("Statistics") or {}
            mem = b.get("Memory") or {}
            params = (b.get("Parameters") or "").strip()
            rows.append((b["Method"], params, st.get("Mean"), st.get("StandardDeviation"), mem.get("BytesAllocatedPerOperation")))
            total += 1
        sections.append((cls, rows))

    lines = []
    lines.append("# Benchmark results\n")
    lines.append("Generated by `benchmarks/make-results-doc.py` from a BenchmarkDotNet `--job short --memory` run of the whole suite "
                 f"({total} benchmarks in {len(sections)} classes).\n")
    if host:
        lines.append(f"Environment: BenchmarkDotNet v{host.get('BenchmarkDotNetVersion')}, {host.get('OsVersion')}, {host.get('ProcessorName')}, {host.get('RuntimeVersion')}  ")
        lines.append(f"Logical cores: {host.get('LogicalCoreCount')}, build configuration: {host.get('Configuration')}" + "\n")
    lines.append("**Read these as ratios, not absolute truths.** The short job takes 3 iterations on a shared Windows workstation (Docker Desktop and an IDE "
                 "were running); expect 10-20 % run-to-run noise. Allocation numbers (B/op) are exact and are the figures that matter for the zero-allocation goal. "
                 "The long-job, head-to-head-with-Go numbers of the end-to-end client are in [`performance.md`](performance.md); the allocation protocol and the "
                 "before/after of the response pooling are in [`performance-allocation.md`](performance-allocation.md).\n")
    for cls, rows in sections:
        lines.append(f"## {cls}\n")
        lines.append("| Method | Parameters | Mean | StdDev | Allocated / op |")
        lines.append("|---|---|---:|---:|---:|")
        for m, p, mean, sd, alloc in rows:
            lines.append(f"| {m} | {p} | {fmt_time(mean)} | {fmt_time(sd)} | {fmt_bytes(alloc)} |")
        lines.append("")
    for e in extras:
        lines.append(open(e, encoding="utf-8").read().rstrip() + "\n")
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {out}: {total} benchmarks in {len(sections)} classes")


if __name__ == "__main__":
    main()
